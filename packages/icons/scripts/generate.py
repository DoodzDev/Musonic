#!/usr/bin/env python3
"""Generates src/icons.ts from the mobile app's icon set (apps/mobile/src/components/icons),
the single source of Musonic's icons: the same artwork everywhere (mobile, web, console).

Each React Native component becomes plain SVG markup. Props are replaced by their defaults
(`{color}` → currentColor); a `cond ? A : B` on an attribute and `{flag ? (<A/>) : (<B/>)}` /
`{flag && <A/>}` blocks give two variants: `name` (flag off) and `name-<flag>` (flag on).

    python3 packages/icons/scripts/generate.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "apps/mobile/src/components/icons"
OUT = ROOT / "packages/icons/src/icons.ts"

RENAME = {
    "strokeWidth": "stroke-width", "strokeLinecap": "stroke-linecap",
    "strokeLinejoin": "stroke-linejoin", "fillRule": "fill-rule", "clipRule": "clip-rule",
    "strokeMiterlimit": "stroke-miterlimit", "fillOpacity": "fill-opacity",
    "strokeOpacity": "stroke-opacity", "strokeDasharray": "stroke-dasharray",
}
COLOR_PROPS = {"color", "stroke", "fill", "tint", "accent"}


def kebab(name: str) -> str:
    name = name[:-4] if name.endswith("Icon") else name
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def consts(src: str) -> dict:
    return {m.group(1): m.group(2) for m in re.finditer(r"const ([A-Z_]+)\s*=\s*'([^']*)'", src, re.S)}


def defaults(src: str) -> dict:
    m = re.search(r"export default function \w+\(\{(.*?)\}", src, re.S)
    out = {}
    if m:
        for part in m.group(1).split(","):
            if "=" in part:
                k, v = part.split("=", 1)
                out[k.strip()] = v.strip().strip("'\"")
    return out


def value(expr: str, flags: dict, defs: dict, cs: dict) -> str | None:
    expr = expr.strip()
    t = re.fullmatch(r"(\w+)\s*\?\s*(.+?)\s*:\s*(.+)", expr)
    if t:
        return value(t.group(2) if flags.get(t.group(1)) else t.group(3), flags, defs, cs)
    if re.fullmatch(r"-?[\d.]+", expr):
        return expr
    if re.fullmatch(r"'[^']*'", expr):
        return expr[1:-1]
    if expr in cs:
        return cs[expr]
    if expr in COLOR_PROPS:
        return "currentColor"
    if expr in defs and re.fullmatch(r"-?[\d.]+", defs[expr]):
        return defs[expr]
    m = re.fullmatch(r"(\w+)\s*\+\s*([\d.]+)", expr)
    if m and m.group(1) in defs:
        return str(round(float(defs[m.group(1)]) + float(m.group(2)), 3))
    return None


def render(body: str, flags: dict, defs: dict, cs: dict) -> str | None:
    def block(m):
        cond, a, b = m.group(1), m.group(2), m.group(3) or ""
        return a if flags.get(cond) else b
    body = re.sub(r"\{\s*/\*.*?\*/\s*\}", "", body, flags=re.S)
    body = re.sub(r"\{\s*(\w+)\s*\?\s*\((.*?)\)\s*:\s*(?:\((.*?)\)|null)\s*\}", block, body, flags=re.S)
    body = re.sub(r"\{\s*(\w+)\s*&&\s*(<.*?/>)\s*\}", lambda m: m.group(2) if flags.get(m.group(1)) else "", body, flags=re.S)
    failed = False

    def attr(m):
        nonlocal failed
        v = value(m.group(2), flags, defs, cs)
        if v is None:
            failed = True
            return m.group(0)
        return f'{m.group(1)}="{v}"'
    body = re.sub(r"(\w+)=\{([^{}]*)\}", attr, body)
    if failed or "{" in body:
        return None
    for a, b in RENAME.items():
        body = body.replace(f"{a}=", f"{b}=")
    body = re.sub(r"<(/?)(Path|Circle|Rect|Line|Polyline|Polygon|G|Ellipse)\b", lambda x: f"<{x.group(1)}{x.group(2).lower()}", body)
    return " ".join(body.split())


icons, skipped = {}, []
for f in sorted(SRC.glob("*Icon.tsx")):
    src = f.read_text()
    m = re.search(r'<Svg[^>]*viewBox="([^"]+)"[^>]*>(.*?)</Svg>', src, re.S)
    if not m:
        skipped.append(f.stem)
        continue
    vb, body = m.group(1), m.group(2)
    defs, cs = defaults(src), consts(src)
    flags = sorted(set(re.findall(r"\{\s*(\w+)\s*(?:\?|&&)", body)) | set(re.findall(r"=\{(\w+)\s*\?", body)))
    flags = [x for x in flags if x not in COLOR_PROPS]
    base = render(body, {}, defs, cs)
    if base is None:
        skipped.append(f.stem)
        continue
    icons[kebab(f.stem)] = (vb, base)
    for flag in flags:
        alt = render(body, {flag: True}, defs, cs)
        if alt and alt != base:
            icons[f"{kebab(f.stem)}-{kebab(flag[0].upper() + flag[1:])}"] = (vb, alt)

lines = [
    "// Generated by scripts/generate.py from apps/mobile/src/components/icons: do not edit.",
    "// The mobile icon set is the single source of Musonic's icons.",
    "",
    "export const icons = {",
]
for name, (vb, body) in sorted(icons.items()):
    lines.append(f"  '{name}': {{ viewBox: '{vb}', body: {body!r} }},")
lines += ["} as const;", "", "export type IconName = keyof typeof icons;", ""]
OUT.write_text("\n".join(lines).replace('": {', ": {"))
print(f"{len(icons)} icons written, skipped: {', '.join(skipped) or 'none'}")
